local function resolveModel(registry, value)
    if type(value) ~= 'string' then return nil end
    local needle = value:lower()
    if registry[needle] then return registry[needle], needle end
    for key, entry in pairs(registry) do
        if entry.model:lower() == needle then return entry, key end
    end
end

function Node7ResolveHorseModel(value)
    return resolveModel(Node7HorseModels, value)
end

function Node7NormalizeHorseDefinition(key, entry)
    assert(type(key) == 'string' and type(entry) == 'table' and type(entry.model) == 'string', 'Invalid NODE7 horse definition')
    entry.key = key
    entry.name = entry.name or entry.label
    entry.label = entry.label or entry.name
    entry.price = tonumber(entry.price) or 100
    entry.category = entry.category or 'horse'
    entry.type = entry.type or 'horse'
    entry.hash = entry.hash or joaat(entry.model)
    entry.shop = entry.shop or 'stable'
    entry.metadata = entry.metadata or { health = 100, stamina = 100, bonding = 0 }
    return entry
end

for key, entry in pairs(Node7HorseModels) do
    Node7HorseModels[key] = Node7NormalizeHorseDefinition(key, entry)
end
